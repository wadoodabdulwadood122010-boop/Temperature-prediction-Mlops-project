import pandas as pd
import numpy as np
import pickle
from pathlib import Path
from sklearn.preprocessing import LabelEncoder

# --- CONFIGURATION ---

BASE_DIR = Path(__file__).resolve().parent.parent.parent
INPUT_PATH = BASE_DIR / "data/raw/weather.csv"
OUTPUT_PATH = BASE_DIR / "data/processed/features.csv"
ENCODER_PATH = BASE_DIR / "models/city_encoder.pkl"

def load_data(path):
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {path}")
    
    df = pd.read_csv(path)
    df['date'] = pd.to_datetime(df['date'])
    # Sorting is non-negotiable for time-series operations
    df = df.sort_values(by=['city', 'date']).reset_index(drop=True)
    return df

def add_time_features(df):
    """
    Adds cyclical features so the model understands seasonality.
    """
    df['year'] = df['date'].dt.year
    df['month'] = df['date'].dt.month
    df['day_of_year'] = df['date'].dt.dayofyear

    # Cyclical Encoding (Critical for Dec -> Jan continuity)
    # Maps months to a circle: 12 is close to 1
    df['month_sin'] = np.sin(2 * np.pi * df['month'] / 12)
    df['month_cos'] = np.cos(2 * np.pi * df['month'] / 12)
    
    return df

def add_lag_features(df):
    """
    Generates history-based features.
    """
    # Define the grouping object once to save computation
    grouper_max = df.groupby('city')['temp_max']
    grouper_min = df.groupby('city')['temp_min']

    # 1. Simple Lags (Yesterday, 3 days ago, 7 days ago)
    lags = [1, 3, 7]
    for lag in lags:
        df[f'temp_max_lag_{lag}'] = grouper_max.shift(lag)
        df[f'temp_min_lag_{lag}'] = grouper_min.shift(lag)

    # 2. Rolling Averages (Trends)
    # CRITICAL: We shift by 1 BEFORE rolling to avoid data leakage.
    # We want "Avg of LAST 7 days", not "Avg of last 6 days + today".
    df['rolling_temp_max_7'] = grouper_max.shift(1).transform(lambda x: x.rolling(7).mean())
    df['rolling_temp_min_7'] = grouper_min.shift(1).transform(lambda x: x.rolling(7).mean())
    
    return df

def encode_city(df):
    le = LabelEncoder()
    df['city_encoded'] = le.fit_transform(df['city'])
    
    # Ensure directory exists before saving
    ENCODER_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(ENCODER_PATH, "wb") as f:
        pickle.dump(le, f)
        
    return df

def build_features():
    print("Starting Feature Engineering...")

    # 1. Load
    df = load_data(INPUT_PATH)
    initial_shape = df.shape

    # 2. Transform
    df = add_time_features(df)
    df = add_lag_features(df)
    df = encode_city(df)

    # 3. Clean
    # Drop rows with NaNs generated by lags (first 7 days of data per city)
    df = df.dropna()
    
    # 4. Select Columns
    # Explicitly ordering columns helps with debugging later
    feature_cols = [
        # Metadata
        'date', 'city_encoded', 
        # Time Signals
        'year', 'month_sin', 'month_cos', 'day_of_year',
        # Lag Features
        'temp_max_lag_1', 'temp_max_lag_3', 'temp_max_lag_7',
        'temp_min_lag_1', 'temp_min_lag_3', 'temp_min_lag_7',
        # Rolling Trends
        'rolling_temp_max_7', 'rolling_temp_min_7',
        # External factors
        'rain', 'solar_radiation',
        # Target (Always keep target at the end or clearly named)
        'temp_max' 
    ]
    
    df_final = df[feature_cols]

    # 5. Save
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    df_final.to_csv(OUTPUT_PATH, index=False)

    print("-" * 30)
    print("Feature Engineering Complete.")
    print(f"Original Rows: {initial_shape[0]}")
    print(f"Final Rows:    {df_final.shape[0]} (Dropped {initial_shape[0] - df_final.shape[0]} due to lags)")
    print(f"Saved to:      {OUTPUT_PATH}")

if __name__ == "__main__":
    build_features()